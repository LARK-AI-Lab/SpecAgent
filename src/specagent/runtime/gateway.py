def _text_content(value: Any) -> str:
    if isinstance(value, str):
        return value
    if isinstance(value, list):
        chunks = []
        for block in value:
            if isinstance(block, Mapping) and isinstance(block.get("text"), str):
                chunks.append(block["text"])
        return "\n".join(chunks)
    return json.dumps(value, ensure_ascii=False) if value is not None else ""


def _message(response: Mapping[str, Any]) -> dict[str, Any]:
    choices = response.get("choices")
    if not isinstance(choices, list) or not choices:
        raise ValueError("completion response contains no choices")
    message = choices[0].get("message")
    if not isinstance(message, dict):
        raise ValueError("completion choice contains no message")
    return message


def _tool_calls(response: Mapping[str, Any]) -> list[dict[str, Any]]:
    calls = _message(response).get("tool_calls") or []
    return [dict(call) for call in calls if isinstance(call, Mapping)]


def _reasoning(response: Mapping[str, Any]) -> str | None:
    message = _message(response)
    value = message.get("reasoning_content") or message.get("reasoning")
    return value if isinstance(value, str) and value else None


def _action_from_call(call: Mapping[str, Any]) -> dict[str, Any]:
    function = call.get("function") or {}
    raw_arguments = function.get("arguments") or "{}"
    try:
        arguments = json.loads(raw_arguments) if isinstance(raw_arguments, str) else raw_arguments
    except json.JSONDecodeError:
        arguments = {"_malformed_arguments": raw_arguments}
    return {"tool": function.get("name") or "", "arguments": arguments}


def _action_signature(action: Any) -> str | None:
    """Canonical identity of a tool call for repeat detection; None for
    message steps or malformed actions (which can never be repeats)."""
    if not isinstance(action, Mapping) or "tool" not in action:
        return None
    return json.dumps(
        {"tool": action.get("tool"), "arguments": action.get("arguments")},
        sort_keys=True,
        ensure_ascii=False,
        default=str,
    )


def _is_message_step(step: AgentStep) -> bool:
    return isinstance(step.action, Mapping) and step.action.get("type") == MESSAGE_ACTION_TYPE


def _tool_contracts(request: Mapping[str, Any]) -> dict[str, Any]:
    contracts = {}
    for tool in request.get("tools") or []:
        if not isinstance(tool, Mapping):
            continue
        function = tool.get("function")
        if isinstance(function, Mapping) and function.get("name"):
            contracts[str(function["name"])] = dict(tool)
    return contracts


def _user_messages(request: Mapping[str, Any]) -> list[str]:
    return [
        _text_content(message.get("content"))
        for message in request.get("messages") or []
        if isinstance(message, Mapping) and message.get("role") == "user"
    ]


# Markdown headings in the system prompt; an empty heading is dropped from the verifier's copy.
_SYSTEM_SECTION = re.compile(r"^(#{1,4})[ \t]+(.+?)[ \t]*$", re.MULTILINE)


def _verification_system_constraints(system: str) -> tuple[str, dict[str, int]]:
    """Drop headings that carry no body from the verifier's copy of the system prompt."""
    headings = list(_SYSTEM_SECTION.finditer(system))
    if not headings:
        return system, {"dropped_sections": 0, "dropped_chars": 0, "kept_chars": len(system)}
    kept: list[str] = [system[: headings[0].start()]]
    dropped = 0
    for index, heading in enumerate(headings):
        stop = headings[index + 1].start() if index + 1 < len(headings) else len(system)
        if not system[heading.end() : stop].strip():
            dropped += 1
            continue
        kept.append(system[heading.start() : stop])
    result = "".join(kept)
    return result, {
        "dropped_sections": dropped,
        "dropped_chars": len(system) - len(result),
        "kept_chars": len(result),
    }


def _task_context(
    request: Mapping[str, Any],
    config: GatewayConfig,
    unbound_user_messages: list[str],
    task_instruction: str | None,
    *,
    truncate: bool,
) -> TaskContext:
    """The task as the verifier sees it; ``truncate`` applies the payload's size caps."""
    messages = request.get("messages") or []
    system_chunks = [
        _text_content(message.get("content"))
        for message in messages
        if isinstance(message, Mapping) and message.get("role") == "system"
    ]
    user_chunks = _user_messages(request)
    system, system_receipt = _verification_system_constraints("\n\n".join(system_chunks))
    # The first user message is the task. Later user messages are normally bound as the
    # observation of the reply that preceded them; any that could not be bound are appended here
    # so the verifier still sees every user turn.
    instruction = task_instruction or (user_chunks[0] if user_chunks else FALLBACK_INSTRUCTION)
    task_messages = [instruction, *unbound_user_messages]
    if unbound_user_messages and truncate:
        # Reserve task space so a long later message cannot erase the original goal.
        instruction = instruction[:6000]
        later = "".join(f"\n\n[Later user message]\n{text}" for text in unbound_user_messages)
        instruction += later[-(12000 - len(instruction)) :]
    elif unbound_user_messages:
        instruction += "".join(LATER_CONTEXT_SEPARATOR + text for text in unbound_user_messages)
    if truncate:
        instruction = instruction[:12000]
        system = system[:24000]
    return TaskContext(
        task_id=VERIFIER_TASK_ID,
        instruction=instruction,
        system_constraints=(system,) if system else (),
        tool_contracts=_tool_contracts(request),
        metadata={
            "workspace_dir": config.workspace_dir,
            "task_messages": task_messages,
            "system_constraints_filter": system_receipt,
        },
    )


def _tool_results(request: Mapping[str, Any]) -> dict[str, Any]:
    results = {}
    for message in request.get("messages") or []:
        if not isinstance(message, Mapping) or message.get("role") != "tool":
            continue
        call_id = message.get("tool_call_id")
        if call_id:
            text = _text_content(message.get("content"))
            if str(call_id) in results and results[str(call_id)] != text:
                raise ValueError(f"conflicting tool results for {call_id!r}")
            results[str(call_id)] = text
    return results


def _tool_id_alias(call_id: str) -> str:
    """The id a client that sanitizes tool_call_ids reports back for ``call_id``."""
    if re.fullmatch(r"functions\.[A-Za-z0-9_-]+:\d+", call_id):
        return call_id[:40]
    return (re.sub(r"[^a-zA-Z0-9]", "", call_id) or "sanitizedtoolid")[:40]


def _transcript_call_ids(request: Mapping[str, Any]) -> set[str]:
    """Tool-call ids the client's current transcript still references.

    A delivered call can only ever produce an observation while the client still carries either
    the assistant message that holds the call or the tool result itself.
    """
    ids: set[str] = set()
    for message in request.get("messages") or []:
        if not isinstance(message, Mapping):
            continue
        for call in message.get("tool_calls") or []:
            if isinstance(call, Mapping) and call.get("id"):
                ids.add(str(call["id"]))
        if message.get("tool_call_id"):
            ids.add(str(message["tool_call_id"]))
    return ids


# Verifier history window. It holds at least HISTORY_WINDOW_STEPS steps and slides forward one
# stride at a time, so its length varies in [WINDOW, WINDOW + STRIDE - 1].
HISTORY_WINDOW_STEPS = 64
HISTORY_WINDOW_STRIDE = 32
# Confirmed steps, counted from the newest, that keep recent_observation_chars.
RECENT_FULL_STEPS = 6


def _trim_payload(
    payload: dict[str, Any],
    *,
    window: int = HISTORY_WINDOW_STEPS,
    stride: int = HISTORY_WINDOW_STRIDE,
    recent_observation_chars: int = 0,
    uniform: bool = False,
) -> list[dict[str, Any]]:
    """Apply the payload's size caps and return an auditable omission list.

    ``uniform`` (append-only input) keeps every confirmed step and one observation cap for all of
    them, so consecutive payloads share their prefix.
    """
    omissions: list[dict[str, Any]] = []
    for section in ("confirmed_history", "proposed_trajectory"):
        rows = payload.get(section) or []
        if section == "confirmed_history" and len(rows) > window and not uniform:
            # Advance the window in strides rather than one step at a time: a per-step slide
            # rewrites the first entry of the serialized payload at every boundary, so the
            # provider's prefix cache would miss on every call.
            start = ((len(rows) - window) // stride) * stride
            if start:
                omissions.append({"section": section, "kind": "steps", "removed": start})
                payload[section] = rows[start:]
                rows = payload[section]
        recent_from = (
            0 if section == "proposed_trajectory" or uniform else len(rows) - RECENT_FULL_STEPS
        )
        for position, row in enumerate(rows):
            action = row.get("action")
            is_message = isinstance(action, Mapping) and action.get("type") == MESSAGE_ACTION_TYPE
            # A user's reply is task-critical context; keep far more of it than of tool output.
            limit = 6000 if is_message else 1200
            if recent_observation_chars and position >= recent_from:
                limit = max(limit, recent_observation_chars)
            observation = row.get("observation")
            if isinstance(observation, str) and len(observation) > limit:
                omissions.append(
                    {
                        "section": section,
                        "kind": "observation",
                        "index": row.get("index"),
                        "original_chars": len(observation),
                        "retained_chars": limit,
                    }
                )
                row["observation"] = observation[:limit] + "...[truncated]"
            reasoning = row.get("reasoning")
            if isinstance(reasoning, str) and len(reasoning) > 600:
                omissions.append(
                    {
                        "section": section,
                        "kind": "reasoning",
                        "index": row.get("index"),
                        "original_chars": len(reasoning),
                        "retained_chars": 600,
                    }
                )
                row["reasoning"] = reasoning[:600] + "...[truncated]"
    return omissions


def _truncate_chars(text: str, limit: int) -> str:
    if limit < 1 or len(text) <= limit:
        return text
    mark = "...[truncated]"
    keep = max(0, limit - len(mark))
    return text[:keep] + mark


def _serialized_chars(messages: Sequence[Any]) -> int:
    total = 0
    for message in messages:
        if isinstance(message, Mapping):
            total += len(json.dumps(message, ensure_ascii=False))
    return total


def _filter_tool_calls(response: Mapping[str, Any], allowed_ids: set[str]) -> dict[str, Any]:
    filtered = deepcopy(dict(response))
    message = _message(filtered)
    original_count = len(message.get("tool_calls") or [])
    message["tool_calls"] = [
        call for call in message.get("tool_calls") or [] if str(call.get("id")) in allowed_ids
    ]
    if len(message["tool_calls"]) != original_count:
        # The model reasoned about the full batch, including the dropped calls. Do not let that
        # private suffix leak into the client's transcript after filtering the visible calls.
        message.pop("reasoning_content", None)
        message.pop("reasoning", None)
        message["content"] = None
    return filtered


def _fused_action_response(
    action: Mapping[str, Any], *, model: str, usage: Mapping[str, Any]
) -> dict[str, Any]:
    """Turn a validated replacement action into the assistant response the client expects."""
    call_id = f"call_specagent_{uuid4().hex[:20]}"
    if action.get("type") == MESSAGE_ACTION_TYPE:
        message: dict[str, Any] = {
            "role": "assistant",
            "content": str(action["content"]),
            "tool_calls": None,
        }
        finish_reason = "stop"
    else:
        message = {
            "role": "assistant",
            "content": None,
            "tool_calls": [
                {
                    "id": call_id,
                    "type": "function",
                    "function": {
                        "name": str(action["tool"]),
                        "arguments": json.dumps(action["arguments"], ensure_ascii=False),
                    },
                }
            ],
        }
        finish_reason = "tool_calls"
    return {
        "id": f"chatcmpl-specagent-{uuid4().hex}",
        "object": "chat.completion",
        "created": 0,
        "model": model,
        "choices": [{"index": 0, "message": message, "finish_reason": finish_reason}],
        "usage": dict(usage),
    }


def completion_to_sse(response: Mapping[str, Any]) -> bytes:
    """Convert one buffered Chat Completions response into OpenAI-compatible SSE."""
    choice = response["choices"][0]
    message = choice["message"]
    delta = {
        key: value for key, value in message.items() if key != "tool_calls" and value is not None
    }
    delta.setdefault("role", "assistant")
    if message.get("tool_calls"):
        delta["tool_calls"] = [
            {"index": index, **call} for index, call in enumerate(message["tool_calls"])
        ]
    base = {
        key: response[key]
        for key in ("id", "created", "model", "system_fingerprint")
        if key in response
    }
    first = {
        **base,
        "object": "chat.completion.chunk",
        "choices": [{"index": 0, "delta": delta, "finish_reason": None}],
    }
    final = {
        **base,
        "object": "chat.completion.chunk",
        "choices": [
            {"index": 0, "delta": {}, "finish_reason": choice.get("finish_reason") or "stop"}
        ],
    }
    if response.get("usage") is not None:
        final["usage"] = response["usage"]
    lines = [f"data: {json.dumps(first, ensure_ascii=False)}\n\n"]
    lines.append(f"data: {json.dumps(final, ensure_ascii=False)}\n\n")
    lines.append("data: [DONE]\n\n")
    return "".join(lines).encode("utf-8")


_CONTEXT_OVERFLOW = re.compile(
    r"input \((\d+) tokens\) is longer than the model's context length \((\d+) tokens\)"
)
_CONTEXT_OVERFLOW_PROMPT_TOO_LONG = re.compile(
    r"prompt is too long: (\d+) tokens \S+ (\d+) maximum"
)
# Provider errors that state only the limit, or no numbers at all.
_CONTEXT_OVERFLOW_NO_COUNT = re.compile(r"Range of input length should be \[\d+, \d+\]")
_CONTEXT_OVERFLOW_CODE = re.compile(r'"code":\s*"1261"')
OVERSIZED_RESULT_NOTE = (
    "[This tool result was too large to read ({chars} characters, about {tokens} tokens) and "
    "was dropped. Do not repeat the same call; request a narrower result instead.]"
)


def _context_overflow(error: BaseException) -> tuple[int, int] | None | bool:
    """(used, limit) tokens when the upstream said so, True for an overflow without numbers."""
    match = _CONTEXT_OVERFLOW.search(str(error))
    if match:
        return int(match.group(1)), int(match.group(2))
    match = _CONTEXT_OVERFLOW_PROMPT_TOO_LONG.search(str(error))
    if match:
        return int(match.group(1)), int(match.group(2))
    if isinstance(error, VerifierInputError) and "context length" in str(error):
        return True
    if _CONTEXT_OVERFLOW_NO_COUNT.search(str(error)) or _CONTEXT_OVERFLOW_CODE.search(str(error)):
        return True
    return None


def _overflow_target_chars(serialized: int, overflow: tuple[int, int] | bool) -> int:
    """Characters to keep: scale by the reported token ratio, else halve."""
    if isinstance(overflow, tuple):
        used, limit = overflow
        return int(serialized * 0.8 * limit / max(used, 1))
    return serialized // 2


def _elide_largest(texts: list[str], excess: float) -> dict[int, str]:
    """Replacement notes for the largest texts until ``excess`` characters are removed."""
    replaced: dict[int, str] = {}
    for index in sorted(range(len(texts)), key=lambda i: -len(texts[i])):
        if excess <= 0:
            break
        size = len(texts[index])
        replaced[index] = OVERSIZED_RESULT_NOTE.format(chars=size, tokens=size // 3)
        excess -= size - len(replaced[index])
    return replaced


def _elide_oversized_results(
    request: Mapping[str, Any], *, target_chars: int
) -> dict[str, Any]:
    """Replace the largest tool results until the chat request should fit ``target_chars``."""
    messages = [dict(m) if isinstance(m, Mapping) else m for m in request.get("messages") or []]
    tools = [i for i, m in enumerate(messages) if isinstance(m, dict) and m.get("role") == "tool"]
    texts = [_text_content(messages[i].get("content")) for i in tools]
    excess = _serialized_chars(messages) - target_chars
    for position, note in _elide_largest(texts, excess).items():
        messages[tools[position]]["content"] = note
    return {**request, "messages": messages}


def _elide_payload_observations(
    messages: list[dict[str, Any]], *, target_chars: int
) -> list[dict[str, Any]]:
    """Same for a verifier request: its payload is JSON in the last user message."""
    messages = [dict(m) for m in messages]
    index = max(i for i, m in enumerate(messages) if m.get("role") == "user")
    payload = json.loads(messages[index]["content"])
    rows = [
        row
        for key in ("confirmed_history", "proposed_trajectory")
        for row in payload.get(key) or []
        if isinstance(row, dict) and isinstance(row.get("observation"), str)
    ]
    excess = _serialized_chars(messages) - target_chars
    for position, note in _elide_largest([row["observation"] for row in rows], excess).items():
        rows[position]["observation"] = note
    messages[index]["content"] = json.dumps(payload, ensure_ascii=False)
    return messages


class SpeculativeToolGateway:
    """Single-session prefix verifier for an agent's model/tool loop."""

    def __init__(self, backend: CompletionBackend, config: GatewayConfig) -> None:
        self.backend = backend
        self.config = config
        self.state = _SessionState()
        self._model_calls: list[GatewayModelCall] = []
        self._last_request_hash: str | None = None
        self._last_decision: GatewayDecision | None = None
        self._is_cancelled: Callable[[], bool] | None = None
        self.trace: Callable[[dict[str, Any]], None] | None = None
        # Session-cumulative counters. A rejected repair turn raises before a decision exists,
        # so these live on the gateway and telemetry reads them for every event.
        self._correction_runtime_failures = 0
        self._correction_missing_observations = 0
        self._corrector_reasks = 0
        self._weak_overflow_resamples = 0
        self._strong_overflow_drops = 0
        self._reminted_call_ids = 0

    @property
    def model_calls(self) -> tuple[GatewayModelCall, ...]:
        """Calls incurred in this attempt, including an aborted delivery."""
        return tuple(self._model_calls)

    @property
    def correction_runtime_failure_count(self) -> int:
        """Repair-turn validation failures this session (duplicate ids, unknown tools, schema
        violations, mutation replays, malformed responses)."""
        return self._correction_runtime_failures

    @property
    def correction_missing_observation_count(self) -> int:
        """Repair calls delivered but never bound to an observation."""
        return self._correction_missing_observations

    @property
    def strong_overflow_drop_count(self) -> int:
        """Strong requests retried after oversized results were dropped from them."""
        return self._strong_overflow_drops

    @property
    def weak_overflow_resample_count(self) -> int:
        """Weak calls re-sampled after oversized tool results were dropped from its view."""
        return self._weak_overflow_resamples

    @property
    def corrector_reask_count(self) -> int:
        """Repair turns re-asked once because a call was undeclared or schema-invalid."""
        return self._corrector_reasks

    @property
    def reminted_call_id_count(self) -> int:
        """Strong-authored calls whose already-taken tool_call_id was replaced before delivery."""
        return self._reminted_call_ids

    def _check_cancelled(self) -> None:
        if self._is_cancelled is not None and self._is_cancelled():
            raise ConnectionAbortedError("client disconnected before completion delivery")

    def _complete(
        self,
        request: Mapping[str, Any],
        *,
        phase: str,
        model: str,
        reasoning_effort: str | None = None,
        max_tokens: int | None = None,
    ) -> dict[str, Any]:
        self._check_cancelled()
        started = perf_counter()
        extra_body = {
            "weak_act": self.config.weak_extra_body,
            "strong_verify": self.config.verifier_extra_body,
            "strong_correct": self.config.strong_extra_body,
        }.get(phase)
        cancellation = {"is_cancelled": self._is_cancelled} if self._is_cancelled else {}
        call = {
            "phase": phase,
            "model": model,
            "call_index": len(self._model_calls),
            "model_call_id": uuid4().hex,
            "verification_id": self.state.verification_id,
        }
        if self.trace is not None:
            prepare = getattr(self.backend, "prepare_request", None)
            prepared = (
                prepare(
                    request,
                    model=model,
                    reasoning_effort=reasoning_effort,
                    max_tokens=max_tokens,
                    extra_body=extra_body,
                )
                if prepare
                else None
            )
            self.trace(
                {
                    **call,
                    "event": "model_request",
                    "request": deepcopy(request),
                    "reasoning_effort": reasoning_effort,
                    "max_tokens": max_tokens,
                    "extra_body": deepcopy(extra_body),
                    "verifier_request_snapshot": prepared if phase == "strong_verify" else None,
                    "snapshot_level": "provider_prepared" if prepared is not None else "adapter",
                    "request_hash": content_hash(prepared if prepared is not None else request),
                    "prompt_hash": content_hash(request.get("messages") or []),
                }
            )
        try:
            response = self.backend.complete(
                request,
                model=model,
                reasoning_effort=reasoning_effort,
                max_tokens=max_tokens,
                extra_body=extra_body,
                **cancellation,
            )
        except Exception as error:
            if self.trace is not None:
                self.trace(
                    {
                        **call,
                        "event": "model_error",
                        "error_type": type(error).__name__,
                        "transport_attempts": getattr(error, "transport_attempts", None),
                        "usage_status": "unreported",
                    }
                )
            self._model_calls.append(
                GatewayModelCall(
                    phase=phase,
                    model=model,
                    duration_seconds=perf_counter() - started,
                    usage={},
                    transport_attempts=max(int(getattr(error, "transport_attempts", 1) or 1), 1),
                )
            )
            raise
        self._model_calls.append(
            GatewayModelCall(
                phase=phase,
                model=model,
                duration_seconds=perf_counter() - started,
                usage=dict(response.get("usage") or {}),
                transport_attempts=int(
                    (response.get("_specagent_transport") or {}).get("attempts", 1)
                ),
            )
        )
        if self.trace is not None:
            self.trace({**call, "event": "model_response", "response": deepcopy(response)})
        self._check_cancelled()
        return response

    def _complete_actor(
        self,
        request: Mapping[str, Any],
        *,
        phase: str,
        model: str,
        reasoning_effort: str | None = None,
        max_tokens: int | None = None,
    ) -> dict[str, Any]:
        def complete(req: Mapping[str, Any]) -> dict[str, Any]:
            return self._complete(
                req,
                phase=phase,
                model=model,
                reasoning_effort=reasoning_effort,
                max_tokens=max_tokens,
            )

        if self.config.strong_overflow_drop and phase.startswith("strong"):
            return self._strong_within_context(
                request,
                complete,
                lambda req, target: _elide_oversized_results(req, target_chars=target),
            )
        return complete(request)

    def _strong_within_context(self, request, complete, elide) -> dict[str, Any]:
        """Strong call; on a context-length rejection, drop the largest results and retry.

        The verifier sees the full context, so a result Weak could not hold (and has already
        dropped from its own view) can overflow Strong too. The same note replaces it in this
        request only; up to three shrinking attempts before the error propagates.
        """
        for attempt in range(4):
            try:
                return complete(request)
            except (RuntimeError, VerifierInputError) as error:
                overflow = _context_overflow(error)
                if attempt == 3 or not overflow:
                    raise
                request = elide(
                    request,
                    _overflow_target_chars(
                        _serialized_chars(request.get("messages") or []), overflow
                    ),
                )
                self._strong_overflow_drops += 1
        raise AssertionError("unreachable")

    def _complete_weak_within_context(
        self, request: Mapping[str, Any], **kwargs: Any
    ) -> dict[str, Any]:
        """Weak call; on a context-length rejection, drop oversized results and re-sample.

        A read that returned more than Weak can hold has already run, and every later Weak call
        would fail on it. With ``weak_overflow_resample`` the oversized tool results are
        replaced, in Weak's view only, by a note naming their size, and the next action is
        sampled again. The client transcript is untouched.
        """
        attempts = 3 if self.config.weak_overflow_resample else 0
        while True:
            try:
                return self._complete_actor(request, **kwargs)
            except (RuntimeError, VerifierInputError) as error:
                overflow = _context_overflow(error)
                if attempts == 0 or not overflow:
                    raise
                attempts -= 1
                request = _elide_oversized_results(
                    request,
                    target_chars=_overflow_target_chars(
                        _serialized_chars(request.get("messages") or []), overflow
                    ),
                )
                self._weak_overflow_resamples += 1

    def _weak_request(self, request: Mapping[str, Any]) -> dict[str, Any]:
        result = dict(request)
        if self.config.weak_history_reasoning:
            result["messages"] = self._reattach_reasoning(
                list(request.get("messages") or []), ModelRole.WEAK
            )
        if self.config.weak_review_hint and self.state.review_hint:
            result["messages"] = list(result.get("messages") or []) + [
                {
                    "role": "user",
                    "content": WEAK_REVIEW_HINT_NOTE.format(reason=self.state.review_hint),
                }
            ]
            self.state.review_hint = ""
        return result

    def _decision(self, **kwargs: Any) -> GatewayDecision:
        return GatewayDecision(**kwargs, model_calls=tuple(self._model_calls))

    def _reconcile(self, request: Mapping[str, Any]) -> None:
        """Bind observations the client produced since the last request.

        Tool results bind to the tool step with the same call id. A new user message binds as the
        observation of the most recent reply step that is still waiting for one.
        """
        results = _tool_results(request)
        groups = (self.state.confirmed, self.state.candidate)
        owners: dict[str, set[tuple[int, int]]] = {}
        for group_index, steps in enumerate(groups):
            for index, step in enumerate(steps):
                call_id = str((step.metadata or {}).get("tool_call_id") or "")
                if call_id:
                    for alias in {call_id, _tool_id_alias(call_id)}:
                        owners.setdefault(alias, set()).add((group_index, index))
        for call_id, observation in results.items():
            matches = owners.get(call_id, set())
            if len(matches) > 1:
                raise ValueError(f"ambiguous tool result ID after id normalization: {call_id!r}")
            if matches:
                group_index, index = next(iter(matches))
                step = groups[group_index][index]
                # A result that arrives late for a tombstoned call is still the real
                # observation: bind it and clear the lost marker.
                if step.observation is None or (step.metadata or {}).get("observation_lost"):
                    metadata = {**(step.metadata or {}), "pending": False}
                    metadata.pop("observation_lost", None)
                    groups[group_index][index] = replace(
                        step,
                        observation=observation,
                        metadata=metadata,
                    )

        # Every delivered repair call must come back with a real observation (an error result
        # counts). When the client's transcript no longer references the call at all -- a reset
        # or a compaction dropped the assistant message carrying it -- no result can ever arrive,
        # so it is tombstoned with an explicit lost-observation marker and the run continues.
        referenced = _transcript_call_ids(request)
        for index, step in enumerate(self.state.confirmed):
            if not (
                step.actor is ModelRole.STRONG
                and not _is_message_step(step)
                and (step.metadata or {}).get("pending")
            ):
                continue
            call_id = str((step.metadata or {}).get("tool_call_id") or "")
            if {call_id, _tool_id_alias(call_id)} & referenced:
                continue
            self._correction_missing_observations += 1
            self.state.confirmed[index] = replace(
                step,
                observation=json.dumps(
                    {
                        "error": "missing_observation",
                        "detail": "client transcript dropped this corrector call",
                    },
                    ensure_ascii=False,
                ),
                metadata={
                    **(step.metadata or {}),
                    "pending": False,
                    "observation_lost": True,
                },
            )
        for step in self.state.confirmed:
            if (
                step.actor is ModelRole.STRONG
                and not _is_message_step(step)
                and (step.metadata or {}).get("pending")
            ):
                self._correction_missing_observations += 1
                raise SpecAgentRuntimeError(
                    RuntimeErrorCode.MISSING_OBSERVATION,
                    "corrector tool call "
                    f"{(step.metadata or {}).get('tool_call_id')!r} returned "
                    "with no observation",
                )

        user_chunks = _user_messages(request)
        previous = self.state.user_messages_seen
        if self.state.task_instruction is None and user_chunks:
            self.state.task_instruction = user_chunks[0]
        compacted = user_chunks[: len(previous)] != previous
        new_indices = [
            index
            for tag, _, _, start, end in SequenceMatcher(
                a=previous, b=user_chunks, autojunk=False
            ).get_opcodes()
            if tag in {"insert", "replace"}
            for index in range(start, end)
        ]
        for index in new_indices:
            if not previous and index == 0:
                continue
            text = user_chunks[index]
            if compacted:
                # Summaries and newly arrived turns must not disappear with a shorter transcript.
                self.state.unbound_user_messages.append(text)
                continue
            for position in range(len(self.state.confirmed) - 1, -1, -1):
                step = self.state.confirmed[position]
                if _is_message_step(step) and step.observation is None:
                    self.state.confirmed[position] = replace(step, observation=text)
                    break
            else:
                self.state.unbound_user_messages.append(text)
        self.state.user_messages_seen = user_chunks

    def _mutates(self, action: Any, *, known_tools: set[str] | None) -> bool:
        return action_mutates_state(
            action, known_tools=known_tools, readonly_tools=self.config.readonly_tools
        )

    @staticmethod
    def _known_tools(request: Mapping[str, Any]) -> set[str] | None:
        """Tool names the request offers; None when it offers none (keeps the default gating)."""
        names = set(_tool_contracts(request))
        return names or None

    def _steps(self, response: Mapping[str, Any], actor: ModelRole) -> list[AgentStep]:
        """One step per tool call, or one message step for a text-only response."""
        reasoning = _reasoning(response)
        output_tokens = int((response.get("usage") or {}).get("completion_tokens") or 0)
        calls = _tool_calls(response)
        if not calls:
            # A text-only response is a reply to the user: irrevocable once shown, so it is a
            # pending mutation until Strong accepts it.
            message = _message(response)
            return [
                AgentStep(
                    actor=actor,
                    reasoning=reasoning,
                    action={
                        "type": MESSAGE_ACTION_TYPE,
                        "content": _text_content(message.get("content")),
                    },
                    observation=None,
                    output_tokens=output_tokens,
                    metadata={"pending": True},
                )
            ]
        return [
            AgentStep(
                actor=actor,
                reasoning=reasoning,
                action=_action_from_call(call),
                observation=None,
                output_tokens=output_tokens,
                metadata={"pending": True, "tool_call_id": str(call.get("id") or "")},
            )
            for call in calls
        ]

    @staticmethod
    def _mark_sent(step: AgentStep) -> AgentStep:
        """A reply is 'executed' by returning it; its observation is the user's next message."""
        if _is_message_step(step):
            return replace(step, metadata={**(step.metadata or {}), "pending": False})
        return step

    def _render_candidate(self) -> tuple[dict[str, Any], ...]:
        """The untrimmed candidate, for trajectory audits."""
        return tuple(
            {
                "index": index,
                **render_step(
                    step,
                    consumer=ModelRole.STRONG,
                    policy=ContextPolicy.MIXED_THINKING,
                    force_reasoning=True,
                ),
            }
            for index, step in enumerate(self.state.candidate, start=1)
        )

    def _verify(
        self, request: Mapping[str, Any], *, fallback_accept: int, boundary: str
    ) -> PrefixVerdict:
        """One thinking-off Strong review of the candidate; fails closed on a malformed verdict."""
        config = self.config
        self.state.verification_id = uuid4().hex
        task = _task_context(
            request,
            config,
            self.state.unbound_user_messages,
            self.state.task_instruction,
            truncate=True,
        )
        full_task = _task_context(
            request,
            config,
            self.state.unbound_user_messages,
            self.state.task_instruction,
            truncate=False,
        )
        payload = verification_payload(
            self.state.confirmed,
            self.state.candidate,
            policy=ContextPolicy.MIXED_THINKING,
            task=task,
        )
        source_payload = verification_payload(
            self.state.confirmed,
            self.state.candidate,
            policy=ContextPolicy.MIXED_THINKING,
            task=full_task,
        )
        omissions = _trim_payload(
            payload,
            recent_observation_chars=config.verifier_recent_observation_chars,
            uniform=config.verifier_append_only,
        )
        payload["input_integrity"] = {
            "status": "truncated" if omissions else "complete",
            "profile": "trimmed",
            "omissions": omissions,
            "source_hash": content_hash(source_payload),
            "scope": "runtime-supplied evidence; long content trimmed to size caps",
        }
        if not (config.verifier_history_reasoning and config.verifier_include_reasoning):
            terminal_key = next(reversed(payload), None)
            payload, pruned = prune_payload(
                payload,
                history_reasoning=config.verifier_history_reasoning,
                candidate_reasoning=config.verifier_include_reasoning,
                compaction_summaries=True,
            )
            payload.setdefault("request_evidence_metadata", {})["pruned_context"] = pruned
            # The prune receipt must not displace the payload's terminal field.
            if terminal_key is not None and next(reversed(payload)) != terminal_key:
                payload[terminal_key] = payload.pop(terminal_key)
        if config.verifier_all_tool_contracts:
            invoked = (
                {} if config.verifier_append_only
                else payload.get("invoked_tool_contracts") or {}
            )
            available = {
                name: contract
                for name, contract in sorted((task.tool_contracts or {}).items())
                if name not in invoked
            }
            # Placed before the trajectory so consecutive verifications share it as prefix.
            payload = {
                **{k: v for k, v in payload.items() if k != "proposed_trajectory"},
                "available_tool_contracts": available,
                **({"proposed_trajectory": payload["proposed_trajectory"]}
                   if "proposed_trajectory" in payload else {}),
            }
        if config.verifier_append_only:
            head = ("task", "anchors", "available_tool_contracts", "confirmed_history")
            payload = {
                **{k: payload[k] for k in head if k in payload},
                **{
                    k: v for k, v in payload.items()
                    if k not in head and k != "proposed_trajectory"
                },
                **({"proposed_trajectory": payload["proposed_trajectory"]}
                   if "proposed_trajectory" in payload else {}),
            }
        messages = verifier_messages(payload)
        if config.strict_answer_review:
            messages[0]["content"] = strict_answer_review(messages[0]["content"])
        if config.verifier_answer_checks and (
            boundary == "message" or config.verifier_append_only
        ):
            messages[0]["content"] += "\n\n" + ANSWER_REVIEW_CHECKS
        if config.verifier_all_tool_contracts:
            messages[0]["content"] += "\n\n" + ALL_TOOL_REPLACEMENT_RULES
        if config.verifier_prompt_suffix:
            messages[0]["content"] += "\n\n" + config.verifier_prompt_suffix
        verifier_request = {
            "messages": messages,
            "temperature": 0,
            "enable_thinking": False,
            "response_format": {"type": "json_object"},
        }
        if self.trace is not None:
            self.trace(
                {
                    "event": "verifier_input",
                    "verification_id": self.state.verification_id,
                    "source_payload": source_payload,
                    "submitted_payload": deepcopy(payload),
                    "input_changed": source_payload != payload,
                    "input_integrity": payload.get("input_integrity"),
                    "task_semantics": config.task_semantics,
                    "tool_contracts": deepcopy(task.tool_contracts or {}),
                    "task_messages": (full_task.metadata or {}).get("task_messages"),
                }
            )

        def complete_verify(req: Mapping[str, Any]) -> dict[str, Any]:
            return self._complete(
                req,
                phase="strong_verify",
                model=config.strong_model,
                reasoning_effort=config.verifier_reasoning_effort,
                max_tokens=config.verifier_max_tokens,
            )

        last_raw = ""
        parse_kind = ""
        for retry in (False, True):
            if retry:
                verifier_request["messages"] = [
                    *verifier_request["messages"],
                    {"role": "user", "content": VERIFIER_RETRY_NOTE},
                ]
            try:
                check_input_budget(verifier_request["messages"], config.verifier_max_input_tokens)
            except VerifierInputError as error:
                if self.trace is not None:
                    self.trace(
                        {
                            "event": "verifier_input_error",
                            "status": "input_incomplete",
                            "verification_id": self.state.verification_id,
                            "error": str(error),
                        }
                    )
                raise
            if config.strong_overflow_drop:
                response = self._strong_within_context(
                    verifier_request,
                    complete_verify,
                    lambda req, target: {
                        **req,
                        "messages": _elide_payload_observations(
                            req["messages"], target_chars=target
                        ),
                    },
                )
            else:
                response = complete_verify(verifier_request)
            message = _message(response)
            last_raw = str(message.get("content") or message.get("reasoning_content") or "")
            try:
                return replace(
                    parse_prefix_verdict(last_raw, len(self.state.candidate)),
                    raw=last_raw,
                    verification_id=self.state.verification_id,
                    format_retries=int(retry),
                )
            except VerdictFormatError as error:
                parse_kind = error.kind
            except json.JSONDecodeError:
                choices = response.get("choices") or []
                finish = str(choices[0].get("finish_reason") or "") if choices else ""
                parse_kind = "truncated" if finish == "length" else "unparseable"
            except (TypeError, ValueError):
                parse_kind = "undetermined"
        # Fail closed on the batch that has not been released to the client yet.
        return PrefixVerdict(
            accepted_steps=fallback_accept,
            rejection_code=RejectionCode.OTHER,
            confidence=0.0,
            raw=last_raw,
            reason="The reviewer returned no valid verdict; this is not a proven task error.",
            diagnostic_status="format_failure",
            format_failure_kind=parse_kind or "undetermined",
            verification_id=self.state.verification_id,
            format_retries=1,
        )

    def _with_strong_reasoning(self, messages: list[Any]) -> list[Any]:
        """Strong's view of the transcript.

        Delivered turns carry no reasoning, but thinking-mode tool calling expects a model's prior
        reasoning back on its own turns, so Strong's is re-attached here, matched by tool-call id
        (raw or sanitized) or, for plain replies, by content. With `correction_history_reasoning`
        off every earlier turn's reasoning is dropped instead.
        """
        if not self.config.correction_history_reasoning:
            return [
                (
                    {
                        key: value
                        for key, value in message.items()
                        if key not in ("reasoning_content", "reasoning")
                    }
                    if isinstance(message, Mapping) and message.get("role") == "assistant"
                    else message
                )
                for message in messages
            ]
        return self._reattach_reasoning(messages, ModelRole.STRONG)

    def _reattach_reasoning(self, messages: list[Any], actor: ModelRole) -> list[Any]:
        """Put ``actor``'s own reasoning_content back on its earlier assistant turns."""
        by_call_id: dict[str, str] = {}
        by_reply: dict[str, str] = {}
        # Weak steps stay in the candidate until their boundary is sealed.
        for step in [*self.state.confirmed, *self.state.candidate]:
            if step.actor is not actor or not step.reasoning:
                continue
            call_id = str((step.metadata or {}).get("tool_call_id") or "")
            if call_id:
                by_call_id[call_id] = step.reasoning
                by_call_id[_tool_id_alias(call_id)] = step.reasoning
            elif _is_message_step(step):
                by_reply[str(step.action.get("content") or "")] = step.reasoning
        if not by_call_id and not by_reply:
            return list(messages)
        result: list[Any] = []
        for message in messages:
            if (
                not isinstance(message, Mapping)
                or message.get("role") != "assistant"
                or message.get("reasoning_content")
                or message.get("reasoning")
            ):
                result.append(message)
                continue
            reasoning = None
            for call in message.get("tool_calls") or []:
                reasoning = by_call_id.get(str(call.get("id") or ""))
                if reasoning:
                    break
            if reasoning is None and not message.get("tool_calls"):
                reasoning = by_reply.get(_text_content(message.get("content")))
            if reasoning:
                message = {**message, "reasoning_content": reasoning}
            result.append(message)
        return result

    def _review_note(self) -> str:
        code = self.state.rejection_code.value if self.state.rejection_code else "other"
        note = review_note(
            code=code,
            reason=self.state.rejection_reason,
            rejected_step=self.state.rejected_step,
            discarded_after=self.state.discarded_after_rejected,
            vocabulary=GATEWAY_VOCABULARY,
        )
        if self.config.task_semantics == "qa" and QA_CORRECTION_SUFFIX.strip() not in note:
            note += QA_CORRECTION_SUFFIX
        return note

    def _clear_rejection(self) -> None:
        if self.config.weak_review_hint and self.state.rejection_reason:
            self.state.review_hint = _truncate_chars(self.state.rejection_reason, 300)
        self.state.deferred_correction = False
        self.state.rejection_code = None
        self.state.rejection_reason = ""
        self.state.rejected_step = None
        self.state.discarded_after_rejected = 0

    def _strong_request(
        self, request: Mapping[str, Any], note: str | None = None
    ) -> dict[str, Any]:
        """The client's transcript as Strong sees it, with an optional trailing runtime note.

        The note is appended as a *user* turn after the transcript rather than as a system
        message, so the transcript prefix stays byte-identical across repairs in a session and the
        provider's prompt cache covers it; some chat templates hoist system messages to the
        front, which would break the cached prefix on every repair.
        """
        strong_request = dict(request)
        history = self._with_strong_reasoning(request.get("messages") or [])
        strong_request["messages"] = (
            history if note is None else [*history, {"role": "user", "content": note}]
        )
        return strong_request

    def _strong_turn(self, strong_request: dict[str, Any]) -> dict[str, Any]:
        return self._complete_actor(
            strong_request,
            phase="strong_correct",
            model=self.config.strong_model,
            reasoning_effort=self.config.correction_reasoning_effort,
            max_tokens=self.config.corrector_max_tokens,
        )

    def _correction(self, request: Mapping[str, Any]) -> _CorrectionResult:
        """Strong's one repair turn: delivered response, committed actions, counts."""
        if self.state.strong_takeover:
            # The handoff note goes on the first takeover turn only; later turns are plain Strong
            # turns over the client transcript.
            prompt = None if self.state.takeover_note_sent else WEAK_BUDGET_NOTE
            self.state.takeover_note_sent = True
        else:
            prompt = self._review_note()
        strong_request = self._strong_request(request, prompt)
        response = self._strong_turn(strong_request)
        problem = (
            self._invalid_corrector_call(response, request)
            if self.config.corrector_reask_invalid_call
            else None
        )
        if problem is not None:
            # One re-ask instead of failing the whole turn: the call has not run, and the
            # validation below still fails closed if the second answer is invalid too.
            self._corrector_reasks += 1
            strong_request["messages"] = [
                *strong_request["messages"],
                {
                    "role": "user",
                    "content": f"{problem} Use only the tools declared in this request.",
                },
            ]
            response = self._strong_turn(strong_request)

        def regenerate(note: str) -> dict[str, Any]:
            # The retry note rides in the same trailing user turn as the review prompt.
            text = note if prompt is None else f"{prompt}\n\n{note}"
            return self._strong_turn(self._strong_request(request, text))

        return self._commit_correction(response, request, regenerate=regenerate)

    def _commit_correction(
        self,
        response: dict[str, Any],
        request: Mapping[str, Any],
        *,
        regenerate: Callable[[str], dict[str, Any]],
    ) -> _CorrectionResult:
        """Validate a Strong repair turn, commit it to history, and shape it for delivery.

        Every tool call of the turn is kept in provider order, validated per call, and delivered
        once.
        """
        emitted_calls = len(_tool_calls(response))
        suppressed_reply: str | None = None
        withheld_replays = 0
        try:
            response = self._remint_colliding_call_ids(response)
            retried = False
            while True:
                withheld = self._validate_correction_turn(response, request)
                if not withheld:
                    break
                withheld_replays += len(withheld)
                keep = {
                    str(c.get("id") or "") for c in _tool_calls(response)
                } - {str(w["call_id"]) for w in withheld}
                response = _filter_tool_calls(response, keep)
                if _tool_calls(response) or retried:
                    break
                # Every emitted call replayed an executed mutation. Retry once, telling Strong
                # which mutations already took effect; a second all-replay turn is delivered
                # as-is (it becomes a reply) rather than aborting.
                retried = True
                names = ", ".join(sorted({str(w["tool"]) for w in withheld}))
                response = regenerate(
                    "Correction retry: every tool call in your previous turn was "
                    "withheld because it replayed an already-executed mutation "
                    f"({names}). Those actions already took effect; do not issue "
                    "them again. Emit the next different action, or reply if the "
                    "task is already complete."
                )
                emitted_calls = len(_tool_calls(response))
                response = self._remint_colliding_call_ids(response)
            response, suppressed_reply = self._suppress_correction_reply(response)
        except SpecAgentRuntimeError:
            raise  # _correction_failure already counted it
        except (TypeError, ValueError) as error:
            raise self._correction_failure(
                RuntimeErrorCode.FORMAT_ERROR,
                f"malformed corrector response: {error}",
            ) from error
        correction_steps = [
            self._mark_sent(step) for step in self._steps(response, ModelRole.STRONG)
        ]
        self.state.confirmed.extend(correction_steps)
        self._clear_rejection()
        return _CorrectionResult(
            response=self._deliverable(response),
            actions=tuple(step.action for step in correction_steps),
            tool_call_count=emitted_calls,
            suppressed_reply=suppressed_reply,
            withheld_replays=withheld_replays,
        )

    def _commit_executed(self, accepted: int, prior_length: int) -> None:
        """Keep the steps that already ran (flagging the rejected ones); drop unsent ones."""
        keep = min(accepted, prior_length)
        self.state.confirmed.extend(
            step
            if index < keep
            else replace(
                step,
                reasoning=None,
                metadata={**(step.metadata or {}), "verifier_rejected": True},
            )
            for index, step in enumerate(self.state.candidate[:prior_length])
        )
        self.state.candidate.clear()
        self._clear_rejection()

    @staticmethod
    def _suppress_correction_reply(
        response: Mapping[str, Any]
    ) -> tuple[dict[str, Any], str | None]:
        """A repair turn carrying tool calls does not also deliver a public reply.

        The calls are the repair; a simultaneous reply would publish text the runtime never
        verified alongside actions it did. The withheld content stays in the private trace and is
        mirrored on the decision as `correction_suppressed_reply`.
        """
        if not _tool_calls(response):
            return dict(response), None
        content = _text_content(_message(response).get("content"))
        if not content.strip():
            return dict(response), None
        delivered = deepcopy(response)
        _message(delivered)["content"] = None
        return delivered, content

    def _correction_failure(
        self, code: RuntimeErrorCode, message: str
    ) -> SpecAgentRuntimeError:
        self._correction_runtime_failures += 1
        return SpecAgentRuntimeError(code, message)

    @staticmethod
    def _deliverable(response: dict[str, Any]) -> dict[str, Any]:
        """The response as it enters the client's transcript: without hidden reasoning.

        The reasoning was produced against context the client never saw (the withheld plan for
        Weak, the review note for Strong). It stays in the gateway's own history (re-attached by
        _reattach_reasoning) and in the private trace; it is never delivered.
        """
        delivered = deepcopy(response)
        message = _message(delivered)
        message.pop("reasoning_content", None)
        message.pop("reasoning", None)
        return delivered

    def _delivered_call_ids(self) -> set[str]:
        """tool_call_ids already released to the client, plus their sanitized aliases."""
        ids: set[str] = set()
        for step in (*self.state.confirmed, *self.state.candidate):
            call_id = str((step.metadata or {}).get("tool_call_id") or "")
            if call_id:
                ids.add(call_id)
                ids.add(_tool_id_alias(call_id))
        return ids

    def _executed_mutations(self, known_tools: set[str] | None) -> set[str]:
        """Canonical forms of mutations that already ran, for replay detection."""
        out: set[str] = set()
        for step in (*self.state.confirmed, *self.state.candidate):
            if _is_message_step(step) or step.observation is None:
                continue
            if self._mutates(step.action, known_tools=known_tools):
                out.add(json.dumps(step.action, ensure_ascii=False, sort_keys=True))
        return out

    @staticmethod
    def _invalid_corrector_call(
        response: Mapping[str, Any], request: Mapping[str, Any]
    ) -> str | None:
        """The first repair call naming an undeclared tool or failing its schema, if any."""
        contracts = _tool_contracts(request)
        for index, call in enumerate(_tool_calls(response)):
            action = _action_from_call(call)
            tool = str(action.get("tool") or "")
            if tool not in contracts:
                return f"Your call {tool!r} is not an available tool."
            check = schema_check({"action": action}, index, contracts)
            if check.get("status") != "valid":
                return f"Your call {tool!r} has invalid arguments: {check.get('detail') or check}."
        return None

    def _remint_colliding_call_ids(self, response: dict[str, Any]) -> dict[str, Any]:
        """Give a Strong-authored call a fresh id when its id is already taken.

        The id is only the model's label for pairing the call with its result, and models reuse
        labels across turns. Nothing has run yet, so renaming is safe; a real replay -- a
        mutation identical to one already executed -- is still caught by
        ``_validate_correction_turn``.
        """
        calls = _tool_calls(response)
        if not calls:
            return response
        taken = self._delivered_call_ids()
        renamed: dict[int, str] = {}
        for index, call in enumerate(calls):
            call_id = str((call or {}).get("id") or "")
            if call_id and (call_id in taken or _tool_id_alias(call_id) in taken):
                renamed[index] = f"call_specagent_{uuid4().hex[:20]}"
            final = renamed.get(index, call_id)
            taken.update({final, _tool_id_alias(final)})
        if not renamed:
            return response
        reminted = deepcopy(response)
        message = _message(reminted)
        message["tool_calls"] = [
            {**call, "id": renamed[index]} if index in renamed else call
            for index, call in enumerate(_tool_calls(reminted))
        ]
        self._reminted_call_ids += len(renamed)
        if self.trace is not None:
            self.trace(
                {
                    "event": "corrector_call_ids_reminted",
                    "renamed": {str(calls[i].get("id")): new for i, new in renamed.items()},
                }
            )
        return reminted

    def _validate_correction_turn(
        self, response: Mapping[str, Any], request: Mapping[str, Any]
    ) -> list[dict[str, Any]]:
        """Per-call contract for a repair turn; returns calls withheld from delivery.

        Identity faults (missing/duplicate tool_call_id) always fail closed -- the client cannot
        pair observations for them. Schema and unknown-tool checks apply only under
        strict_action_validation. A mutation identical to one already executed is never
        delivered: strict mode fails closed; otherwise the call is withheld so the rest of the
        turn can still deliver.
        """
        calls = _tool_calls(response)
        withheld: list[dict[str, Any]] = []
        if not calls:
            return withheld
        contracts = _tool_contracts(request)
        known_tools = self._known_tools(request)
        delivered_ids = self._delivered_call_ids()
        executed_mutations = self._executed_mutations(known_tools)
        seen: set[str] = set()
        for index, call in enumerate(calls):
            call_id = str((call or {}).get("id") or "")
            if not call_id:
                raise self._correction_failure(
                    RuntimeErrorCode.FORMAT_ERROR,
                    f"corrector call {index} carries no tool_call_id",
                )
            if call_id in seen or call_id in delivered_ids:
                raise self._correction_failure(
                    RuntimeErrorCode.REPLAY_DIVERGENCE,
                    f"corrector tool_call_id {call_id!r} duplicates a delivered call",
                )
            seen.add(call_id)
            delivered_ids.add(_tool_id_alias(call_id))
            action = _action_from_call(call)
            tool = str(action.get("tool") or "")
            if self.config.strict_action_validation:
                if tool not in contracts:
                    raise self._correction_failure(
                        RuntimeErrorCode.FORMAT_ERROR,
                        f"corrector call {index} invokes unknown tool {tool!r}",
                    )
                check = schema_check({"action": action}, index, contracts)
                if check.get("status") != "valid":
                    raise self._correction_failure(
                        RuntimeErrorCode.FORMAT_ERROR,
                        f"corrector call {index} fails schema validation: "
                        f"{check.get('detail') or check}",
                    )
            if self._mutates(action, known_tools=known_tools):
                key = json.dumps(action, ensure_ascii=False, sort_keys=True)
                if key in executed_mutations:
                    if self.config.strict_action_validation:
                        raise self._correction_failure(
                            RuntimeErrorCode.REPLAY_DIVERGENCE,
                            f"corrector call {index} replays an already-executed "
                            f"mutation {tool!r}",
                        )
                    withheld.append(
                        {
                            "index": index,
                            "call_id": call_id,
                            "tool": tool,
                            "kind": "mutation_replay",
                        }
                    )
                    continue
                executed_mutations.add(key)
        return withheld

    def _fused_correction(
        self, request: Mapping[str, Any], verdict: PrefixVerdict, boundary: str
    ) -> tuple[dict[str, Any] | None, PrefixVerdict]:
        """Commit a schema-valid action emitted by the verifier, or discard it.

        Returns ``(response, verdict)``. The response is None when no action was committed; the
        returned verdict then records in ``replacement_validation_failure_kind`` which guard
        failed. A discarded action never reaches the repair prompt and never costs a verifier
        retry: the caller falls through to Strong repair exactly as if the model had emitted null.
        """
        if (
            boundary not in self.config.fuse_correction_boundaries
            or verdict.replacement_action is None
        ):
            return None, verdict
        action = dict(verdict.replacement_action)
        rejected_action = (self.state.rejected_step or {}).get("action") or {}
        kind = ""
        if action.get("type") == MESSAGE_ACTION_TYPE:
            kind = "message_replacement"
        else:
            contracts = _tool_contracts(request)
            if self.config.strict_action_validation:
                if (
                    len(json.dumps(action, ensure_ascii=False))
                    > MAX_REPLACEMENT_ACTION_CHARS
                ):
                    kind = "oversized_replacement"
                elif str(action.get("tool") or "") not in contracts:
                    kind = "unknown_tool"
                elif schema_check({"action": action}, 1, contracts).get("status") != "valid":
                    kind = "schema_invalid"
            if not kind:
                if action == rejected_action:
                    kind = "replays_rejected"
                elif self._mutates(action, known_tools=self._known_tools(request)) and (
                    json.dumps(action, ensure_ascii=False, sort_keys=True)
                    in self._executed_mutations(self._known_tools(request))
                    # A delivered mutation has run even if its result is not back yet.
                    or any(step.action == action for step in self.state.confirmed)
                ):
                    kind = "mutation_replay"
        if kind:
            return None, replace(
                verdict,
                replacement_action=None,
                replacement_validation_failure_kind=kind,
            )
        usage = self._model_calls[-1].usage if self._model_calls else {}
        response = _fused_action_response(action, model=self.config.strong_model, usage=usage)
        steps = [self._mark_sent(step) for step in self._steps(response, ModelRole.STRONG)]
        if len(steps) != 1:
            return None, replace(
                verdict,
                replacement_action=None,
                replacement_validation_failure_kind="malformed_replacement",
            )
        self.state.confirmed.extend(steps)
        if self.trace is not None:
            self.trace(
                {
                    "event": "fused_correction",
                    "verification_id": verdict.verification_id,
                    "action": deepcopy(action),
                }
            )
        self._clear_rejection()
        return response, verdict

    def _repair(
        self,
        request: Mapping[str, Any],
        verdict: PrefixVerdict,
        boundary: str,
        common: Mapping[str, Any],
        **extra: Any,
    ) -> GatewayDecision:
        """A rejection's repair: the verifier's replacement when it passes, else one Strong turn."""
        response, salvaged_verdict = self._fused_correction(request, verdict, boundary)
        if response is not None:
            return self._decision(
                response=response,
                source="strong_fused_correction",
                correction_action=self.state.confirmed[-1].action,
                correction_actions=(self.state.confirmed[-1].action,),
                **extra,
                **common,
            )
        correction = self._correction(request)
        return self._decision(
            response=correction.response,
            source="strong_correction",
            correction_action=correction.actions[0],
            correction_actions=correction.actions,
            corrector_generation_count=1,
            correction_tool_call_count=correction.tool_call_count,
            correction_suppressed_reply=correction.suppressed_reply,
            correction_withheld_replays=correction.withheld_replays,
            **extra,
            **{**common, "verdict": salvaged_verdict},
        )

    def _correction_decision(self, request: Mapping[str, Any], source: str) -> GatewayDecision:
        correction = self._correction(request)
        return self._decision(
            response=correction.response,
            source=source,
            correction_action=correction.actions[0],
            correction_actions=correction.actions,
            corrector_generation_count=1,
            correction_tool_call_count=correction.tool_call_count,
            correction_suppressed_reply=correction.suppressed_reply,
        )

    def handle(
        self,
        request: Mapping[str, Any],
        *,
        deliver: Callable[[GatewayDecision], None] | None = None,
        is_cancelled: Callable[[], bool] | None = None,
    ) -> GatewayDecision:
        self._model_calls = []
        if is_cancelled is not None and is_cancelled():
            raise ConnectionAbortedError("client disconnected before request processing")
        request_hash = sha256(
            json.dumps(request, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode()
        ).hexdigest()
        if request_hash == self._last_request_hash and self._last_decision is not None:
            # A client retry of the request just answered gets the same answer, at no cost.
            decision = replace(self._last_decision, source="cached_replay", model_calls=())
            if deliver is not None:
                deliver(decision)
            return decision
        state_before_request = deepcopy(self.state)
        self._is_cancelled = is_cancelled
        try:
            decision = self._handle(request)
            self._check_cancelled()
            if deliver is not None:
                deliver(decision)
        except Exception:
            self.state = state_before_request
            raise
        finally:
            self._is_cancelled = None
        self._last_request_hash = request_hash
        self._last_decision = decision
        return decision

    def _handle(self, request: Mapping[str, Any]) -> GatewayDecision:
        self._model_calls = []
        self._reconcile(request)
        budget = self.config.strong_takeover_after_tool_results
        if budget and not self.state.strong_takeover and sum(
            1 for message in (request.get("messages") or [])
            if isinstance(message, Mapping) and message.get("role") == "tool"
        ) >= budget:
            # Everything Weak delivered has already run; keep it and hand over.
            pending = len(self.state.candidate)
            self._commit_executed(pending, pending)
            self.state.strong_takeover = True
        if self.state.strong_takeover:
            return self._correction_decision(request, "strong_takeover")
        if self.state.deferred_correction:
            return self._correction_decision(request, "strong_correction")

        weak_response = self._complete_weak_within_context(
            self._weak_request(request),
            phase="weak_act",
            model=self.config.weak_model,
            reasoning_effort=self.config.weak_reasoning_effort,
        )
        current = self._steps(weak_response, ModelRole.WEAK)
        prior_length = len(self.state.candidate)
        self.state.candidate.extend(current)
        is_message = any(_is_message_step(step) for step in current)
        known_tools = self._known_tools(request)
        mutating = any(self._mutates(step.action, known_tools=known_tools) for step in current)
        if self.config.repeat_call_guard and not is_message and current:
            seen = {
                _action_signature(step.action)
                for step in [*self.state.confirmed, *self.state.candidate[:prior_length]]
            }
            seen.discard(None)
            if all(_action_signature(step.action) in seen for step in current):
                # Every drafted call replays an already executed call: confirm the delivered
                # prefix, withhold the repeated batch, and repair now.
                candidate_snapshot = self._render_candidate()
                self.state.confirmed.extend(
                    self._mark_sent(step)
                    for step in self.state.candidate[:prior_length]
                )
                self.state.candidate.clear()
                first_repeat = dict(candidate_snapshot[prior_length])
                repeated = json.dumps(first_repeat, ensure_ascii=False)[:200]
                self.state.rejection_reason = (
                    f"All {len(current)} drafted calls repeat calls already executed in this run "
                    f"({repeated}); the earlier observation already holds the requested "
                    "information. Use it or reply instead of re-querying."
                )
                self.state.rejected_step = first_repeat
                self.state.rejection_code = RejectionCode.WRONG_STEP
                correction = self._correction(request)
                return self._decision(
                    response=correction.response,
                    source="strong_correction",
                    correction_action=correction.actions[0],
                    correction_actions=correction.actions,
                    corrector_generation_count=1,
                    correction_tool_call_count=correction.tool_call_count,
                    correction_suppressed_reply=correction.suppressed_reply,
                    repeat_rejected=len(current),
                    candidate_length=len(candidate_snapshot),
                    mutating=mutating,
                    boundary="repeat",
                )

        if is_message:
            boundary = "message"
        elif mutating:
            boundary = "mutation"
        elif len(self.state.candidate) >= self.config.horizon:
            # K reads commit without review.
            candidate_snapshot = self._render_candidate()
            accepted = len(self.state.candidate)
            self.state.confirmed.extend(self._mark_sent(step) for step in self.state.candidate)
            self.state.candidate.clear()
            return self._decision(
                response=self._deliverable(weak_response),
                source="runtime_auto_accept",
                candidate_length=accepted,
                mutating=False,
                boundary="horizon",
                verifier_accepted_steps=accepted,
                candidate_steps=candidate_snapshot,
            )
        else:
            return self._decision(
                response=self._deliverable(weak_response),
                source="weak_read",
                candidate_length=len(self.state.candidate),
                mutating=False,
            )

        candidate_snapshot = self._render_candidate()
        verdict = self._verify(request, fallback_accept=prior_length, boundary=boundary)
        accepted = verdict.accepted_steps
        candidate_length = len(self.state.candidate)
        if accepted < candidate_length:
            self.state.rejection_reason = verdict.reason
            self.state.rejected_step = dict(candidate_snapshot[accepted])
            self.state.discarded_after_rejected = candidate_length - accepted - 1
        common = {
            "verdict": verdict,
            "candidate_length": candidate_length,
            "mutating": mutating,
            "boundary": boundary,
            "verifier_accepted_steps": accepted,
            "candidate_steps": candidate_snapshot,
        }

        if accepted < prior_length:
            # The rejected step was already executed by the client in an earlier request. Keep
            # the executed prefix (flagged), drop the unexecuted batch, and repair now.
            executed = self.state.candidate[:prior_length]
            self.state.confirmed.extend(
                step
                if index < accepted
                else replace(
                    step,
                    reasoning=None,
                    metadata={**(step.metadata or {}), "verifier_rejected": True},
                )
                for index, step in enumerate(executed)
            )
            self.state.candidate.clear()
            self.state.rejection_code = verdict.rejection_code or RejectionCode.OTHER
            return self._repair(
                request,
                verdict,
                boundary,
                common,
                executed_rejected_steps=prior_length - accepted,
            )

        accepted_steps = self.state.candidate[:accepted]
        if accepted < candidate_length and accepted > prior_length:
            accepted_steps = [
                step if index < prior_length else replace(step, reasoning=None)
                for index, step in enumerate(accepted_steps)
            ]
        self.state.confirmed.extend(self._mark_sent(step) for step in accepted_steps)
        self.state.candidate = self.state.candidate[accepted:]
        if accepted == candidate_length:
            self.state.candidate.clear()
            return self._decision(
                response=self._deliverable(weak_response),
                source="weak_verified",
                **common,
            )

        self.state.rejection_code = verdict.rejection_code or RejectionCode.OTHER
        accepted_current = accepted - prior_length
        self.state.candidate.clear()
        if accepted_current:
            # Only reachable with a parallel tool-call batch: release the accepted reads so they
            # produce real observations, then let Strong repair on the next request.
            allowed = {
                str((step.metadata or {}).get("tool_call_id") or "")
                for step in current[:accepted_current]
            }
            self.state.deferred_correction = True
            return self._decision(
                response=self._deliverable(_filter_tool_calls(weak_response, allowed)),
                source="weak_partial_then_correction",
                **common,
            )
        return self._repair(request, verdict, boundary, common)
