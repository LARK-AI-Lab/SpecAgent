@dataclass(frozen=True, slots=True)
class GatewayConfig:
    weak_model: str
    strong_model: str
    # Draft batching cap: a candidate of K reads commits without review.
    horizon: int = 4
    weak_reasoning_effort: str = "low"
    verifier_reasoning_effort: str | None = None
    correction_reasoning_effort: str = "high"
    verifier_max_tokens: int = 1024
    # Output cap for every Strong repair turn. Providers without a separate thinking budget count
    # reasoning against it, so it doubles as their thinking budget.
    corrector_max_tokens: int = 16384
    # Conservative serialized-size bound on the verifier request; None disables the check.
    verifier_max_input_tokens: int | None = None
    # Role-specific request-body overlays (e.g. chat_template_kwargs). None keeps the incoming
    # request body; a dict replaces its thinking-control keys so one role's setting cannot leak
    # onto the other.
    weak_extra_body: Mapping[str, Any] | None = None
    strong_extra_body: Mapping[str, Any] | None = None
    verifier_extra_body: Mapping[str, Any] | None = None
    # Workspace root shown to the verifier as anchors.workspace_dir; empty omits the anchor.
    workspace_dir: str = ""
    # One of TASK_SEMANTICS.
    task_semantics: str = "generic"
    # Tools that are read-only although their name looks like a write (e.g. a command runner
    # whose server only allows listing and reading). Without this every such call is reviewed.
    readonly_tools: tuple[str, ...] = ()
    # Verifier payload: keep the candidate steps' own reasoning, and committed steps' reasoning.
    verifier_include_reasoning: bool = True
    verifier_history_reasoning: bool = True
    # Keep earlier turns' reasoning in the Strong repair turn's copy of the transcript.
    correction_history_reasoning: bool = True
    # Re-attach Weak's own reasoning to its earlier turns in the Weak request. Draft reasoning is
    # not delivered to the client, so the replayed history otherwise lacks it; a small thinking
    # model then tends to emit its tool call inside the reasoning block and return nothing.
    weak_history_reasoning: bool = False
    # Observation cap for the batch under review and the most recent confirmed steps (the rest
    # keep 1200 characters). 0 applies the same cap everywhere.
    verifier_recent_observation_chars: int = 0
    # Append-only verifier input: every review repeats the previous one's prefix so the provider
    # can cache it. Stable head (task, anchors, offered tool schemas, confirmed history without a
    # sliding window and with one per-observation cap), volatile fields after it, the batch under
    # review last.
    verifier_append_only: bool = False
    # Give every verification the schemas of offered tools the candidate has not invoked, so a
    # rejection can be repaired by a replacement that calls any offered tool.
    verifier_all_tool_contracts: bool = False
    # Append ANSWER_REVIEW_CHECKS to reply-boundary reviews (to every review when append-only,
    # so the system prompt stays one cached prefix).
    verifier_answer_checks: bool = False
    # An answer must cover every item asked, each with a supported value.
    strict_answer_review: bool = False
    # Text appended verbatim to the verifier system prompt.
    verifier_prompt_suffix: str | None = None
    # Boundaries at which a verifier replacement_action may commit; elsewhere it is discarded and
    # Strong repairs. Subset of FUSABLE_BOUNDARIES.
    fuse_correction_boundaries: tuple[str, ...] = ("message", "mutation")
    # When False the environment validates action arguments: a schema-invalid or unknown-tool
    # repair call or replacement is delivered and fails as an error observation, as it would in a
    # single-model run. Guards the environment cannot soften still apply: message-shaped
    # replacements, replays of the rejected draft, mutation replays, and duplicate or missing
    # tool_call_ids.
    strict_action_validation: bool = True
    # When every drafted call repeats an already executed call (same tool and arguments), withhold
    # the batch and route it to Strong repair. Reads never reach the verifier under irrevocable
    # review, so this is the only break on a pure-read loop.
    repeat_call_guard: bool = False
    # After a rejection is cleared, show its reason once to the next Weak draft request as a
    # transient user note.
    weak_review_hint: bool = False
    # Re-ask the Strong repair turn once when a call names an undeclared tool or fails its schema,
    # instead of failing the request.
    corrector_reask_invalid_call: bool = False
    # When a Weak request exceeds the context window, replace the largest tool results in Weak's
    # view with a size note and re-sample instead of failing the request.
    weak_overflow_resample: bool = False
    # The same for Strong requests (verifier payload and repair transcript).
    strong_overflow_drop: bool = False
    # Weak step budget: once the transcript holds this many tool results, Strong owns the rest of
    # the task (tools kept, one handoff note). 0 disables it.
    strong_takeover_after_tool_results: int = 0

    def __post_init__(self) -> None:
        if self.horizon < 1:
            raise ValueError("horizon must be positive")
        if self.verifier_max_tokens < 1:
            raise ValueError("verifier_max_tokens must be positive")
        if self.corrector_max_tokens < 1:
            raise ValueError("corrector_max_tokens must be positive")
        if self.verifier_max_input_tokens is not None and self.verifier_max_input_tokens < 1:
            raise ValueError("verifier input limit must be positive")
        if self.task_semantics not in TASK_SEMANTICS:
            raise ValueError("unknown task semantics")
        if not set(self.fuse_correction_boundaries) <= FUSABLE_BOUNDARIES:
            raise ValueError(
                f"fuse_correction_boundaries must be a subset of {sorted(FUSABLE_BOUNDARIES)}"
            )
        if self.verifier_recent_observation_chars < 0:
            raise ValueError("verifier_recent_observation_chars must not be negative")
        if self.strong_takeover_after_tool_results < 0:
            raise ValueError("strong_takeover_after_tool_results must not be negative")
        # The verifier overlay is for sampling/template controls only. Replacing the logical
        # message/tool payload would make the input-budget check and the trace describe a
        # different request from the one sent to the provider.
        forbidden = {
            "messages",
            "tools",
            "functions",
            "model",
            "stream",
            "stream_options",
            "max_tokens",
        }
        if self.verifier_extra_body and forbidden.intersection(self.verifier_extra_body):
            keys = ", ".join(sorted(forbidden.intersection(self.verifier_extra_body)))
            raise ValueError(f"verifier_extra_body cannot override request payload keys: {keys}")


