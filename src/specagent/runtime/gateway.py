"""OpenAI-compatible Weak-led speculation at a tool-call boundary.

The gateway sits between an agent client and the two models. The client owns the transcript and
executes tools, so the gateway sees one model request per agent step and can only decide which
response the client receives. It maps the prefix-commit protocol onto that constraint:

- A read-only tool call is returned immediately; the client executes it and its observation comes
  back in the next request. Such steps accumulate as the speculative candidate.
- The first irrevocable step ends the candidate and triggers one Strong verification before the
  client sees it. Irrevocable steps are state-changing tool calls and text replies to the user (a
  reply cannot be unsent). A reply is recorded as a ``{"type": "message"}`` step whose observation
  is the user's next message.
- A candidate that reaches the horizon ``K`` with reads only commits without review.
- Strong answers with ``{reason, accepted_steps, replacement_action}``. On a rejection a
  schema-valid replacement commits directly; otherwise Strong takes one repair turn, whose full
  multi-call turn commits without re-verification. A rejected read that already ran cannot be
  retracted from the client's transcript: it stays flagged ``verifier_rejected`` and is counted in
  ``GatewayDecision.executed_rejected_steps``.

Known simplification: text emitted alongside tool calls in one response is not verified on its
own; only the tool calls are. Verifying every interim sentence would make every step a boundary.
"""

